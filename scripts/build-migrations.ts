// Writes src/entry/migrations.generated.ts from migrations/*.sql: the hosted install (a Durable
// Object) applies the migrations itself and has no file system. Run: npm run migrations:build
// A test fails when the file and the migrations folder differ.
import { writeFileSync } from "node:fs";
import { readMigrations } from "../src/adapters/node/migrations-fs.ts";

const migrations = readMigrations("migrations");
writeFileSync(
	"src/entry/migrations.generated.ts",
	`// Generated by scripts/build-migrations.ts from migrations/*.sql. Do not edit.
import type { Migration } from "../core/migrations.ts";

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, "\t")};
`,
);
console.log(`Wrote src/entry/migrations.generated.ts (${migrations.length} migrations)`);
